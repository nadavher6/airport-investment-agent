// #74: the long-haul KPI also outputs the number of international flights and passengers, from
// data/t100.json, and the SCORE IS UNCHANGED (golden test against origin/main's values).
import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { getLongHaulShareTool, type CategoryOutput } from "../agent/tools/categoryTools.ts";
import { scoreAirportsTool } from "../agent/tools/scoreAirports.ts";
import { enplanementsDataset, findAirport } from "../data/enplanements/dataset.ts";
import { getT100 } from "../data/t100/dataset.ts";
import { INVESTMENT_KPIS, scoreAirport } from "./investmentScore.ts";

const ctx = { signal: new AbortController().signal };

interface GoldenKpi {
  available: boolean;
  raw: number | null;
  normalized: number | null;
  contribution: number | null;
}
interface GoldenAirport {
  score: number;
  coverage: number;
  missing: string[];
  kpis: Record<string, GoldenKpi>;
}
interface Golden {
  airportCount: number;
  airports: Record<string, GoldenAirport>;
}
/** Generated by golden/generate.ts on origin/main's scoring code, before this change. */
const golden = JSON.parse(readFileSync(new URL("./golden/scores.golden.json", import.meta.url), "utf8")) as Golden;

describe("hand-checked international flights and passengers (T-100, 12 months to 2026-08)", () => {
  // Raw values copied from data/t100.json; the subtraction is shown next to each expectation.
  const cases = [
    // LAX: 266,820 departures, 205,105 domestic -> 61,715 international; 35,936,676 passengers, 24,629,430 domestic -> 11,307,246.
    { code: "LAX", departures: 266820, domesticDepartures: 205105, intlDepartures: 61715, passengers: 35936676, domesticPassengers: 24629430, intlPassengers: 11307246 },
    // JFK (large hub): 212,209 - 126,353 = 85,856 flights; 29,576,848 - 13,673,804 = 15,903,044 passengers.
    { code: "JFK", departures: 212209, domesticDepartures: 126353, intlDepartures: 85856, passengers: 29576848, domesticPassengers: 13673804, intlPassengers: 15903044 },
    // SNA (mid-size): 51,447 - 50,462 = 985 flights; 5,504,528 - 5,392,069 = 112,459 passengers.
    { code: "SNA", departures: 51447, domesticDepartures: 50462, intlDepartures: 985, passengers: 5504528, domesticPassengers: 5392069, intlPassengers: 112459 },
    // 01A (domestic only): 30 - 30 = 0 flights; 41 - 41 = 0 passengers (a real 0, not missing).
    { code: "01A", departures: 30, domesticDepartures: 30, intlDepartures: 0, passengers: 41, domesticPassengers: 41, intlPassengers: 0 },
  ];

  for (const c of cases) {
    it(`${c.code}: international = total - domestic, in the dataset and in the long-haul evidence`, () => {
      const t = getT100(c.code)!;
      expect(t.departures).toBe(c.departures);
      expect(t.domesticDepartures).toBe(c.domesticDepartures);
      expect(t.internationalDepartures).toBe(c.intlDepartures);
      expect(c.departures - c.domesticDepartures).toBe(c.intlDepartures);
      expect(t.passengers).toBe(c.passengers);
      expect(t.domesticPassengers).toBe(c.domesticPassengers);
      expect(t.internationalPassengers).toBe(c.intlPassengers);
      expect(c.passengers - c.domesticPassengers).toBe(c.intlPassengers);

      const record = findAirport(c.code);
      if (record === null) return; // 01A is a T-100 airport the FAA enplanement data may not list
      const ev = scoreAirport(record).kpis.find((k) => k.key === "long_haul")!.evidence!;
      expect(ev.inputs).toMatchObject({
        internationalDepartures: c.intlDepartures,
        departures: c.departures,
        internationalPassengers: c.intlPassengers,
      });
      const fmt = (n: number): string => n.toLocaleString("en-US");
      expect(ev.explanation).toContain(`International flights: ${fmt(c.intlDepartures)} of ${fmt(c.departures)} departures`);
      expect(ev.explanation).toContain(`${fmt(c.intlPassengers)} international passengers`);
    });
  }

  it("LAX's international departures are > 0 and <= departures, for every airport that has the figure", () => {
    const lax = getT100("LAX")!;
    expect(lax.internationalDepartures).toBeGreaterThan(0);
    expect(lax.internationalDepartures).toBeLessThanOrEqual(lax.departures);
  });

  it("an airport whose T-100 rows have no domestic figure gets null, not 0 (NIP: 3 departures)", () => {
    const nip = getT100("NIP")!;
    expect(nip.departures).toBe(3);
    expect(nip.internationalDepartures).toBeNull();
    expect(nip.internationalPassengers).toBeNull();
  });

  it("get_long_haul_share(['LAX','SNA']) returns the counts in each airport's evidence inputs", async () => {
    const r = await getLongHaulShareTool.run({ airport_codes: ["LAX", "SNA"] }, ctx);
    if (!r.ok) throw new Error("expected ok");
    const out = r.output as unknown as CategoryOutput;
    const by = Object.fromEntries(out.airports.map((a) => [a.airportCode, a.evidence!.inputs]));
    expect(by.LAX).toMatchObject({ internationalDepartures: 61715, departures: 266820, internationalPassengers: 11307246 });
    expect(by.SNA).toMatchObject({ internationalDepartures: 985, departures: 51447, internationalPassengers: 112459 });
    expect(getLongHaulShareTool.description).toContain("internationalDepartures");
  });

  it("score_airports' long-haul evidence carries them too", async () => {
    const r = await scoreAirportsTool.run({ airport_codes: ["LAX"] }, ctx);
    if (!r.ok) throw new Error("expected ok");
    const out = r.output as unknown as { ranking: Array<{ breakdown: Record<string, { evidence: { inputs: Record<string, unknown> } }> }> };
    expect(out.ranking[0]!.breakdown.long_haul!.evidence.inputs).toMatchObject({ internationalDepartures: 61715, departures: 266820 });
  });
});

describe("golden: the score is unchanged by #74 (values generated from origin/main's scoring code)", () => {
  it("covers every airport in the FAA dataset", () => {
    expect(Object.keys(golden.airports).sort()).toEqual(Object.keys(enplanementsDataset.airports).sort());
    expect(golden.airportCount).toBe(Object.keys(golden.airports).length);
  });

  it("every airport's composite, coverage and every KPI's raw value, sub-score and contribution are identical", () => {
    const keys = INVESTMENT_KPIS.map((k) => k.key);
    for (const [code, record] of Object.entries(enplanementsDataset.airports)) {
      const want = golden.airports[code]!;
      const got = scoreAirport(record);
      expect(got.score, `${code} composite`).toBe(want.score);
      expect(got.coverage, `${code} coverage`).toBe(want.coverage);
      expect([...got.missing], `${code} missing`).toEqual(want.missing);
      expect(got.kpis.map((k) => k.key)).toEqual(keys);
      for (const k of got.kpis) {
        const w = want.kpis[k.key]!;
        expect({ available: k.available, raw: k.raw, normalized: k.normalized, contribution: k.contribution }, `${code} ${k.key}`).toEqual(w);
      }
    }
  });
});
